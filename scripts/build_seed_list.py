GH_REPO = re.compile(r"github\.com/([A-Za-z0-9-]+)/([A-Za-z0-9_.-]+)")
GH_PAGES = {"orgs", "search", "topics", "sponsors", "apps", "marketplace"}


def get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "holt-seed-builder"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return resp.read()


def repo_from(url: str) -> str | None:
    m = GH_REPO.search(url)
    if not m:
        return None
    owner, name = m.group(1), m.group(2).removesuffix(".git")
    if owner.lower() in GH_PAGES:
        return None
    return f"{owner}/{name}"


def github_parts(url: str) -> list[str]:
    path = url.split("github.com/", 1)[1].split("#")[0].split("?")[0]
    parts = [p for p in path.split("/") if p]
    return parts[1:2] if parts[:1] == ["orgs"] else parts


